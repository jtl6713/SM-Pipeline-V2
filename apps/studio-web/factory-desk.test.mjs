import test from "node:test";
import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));

test("Factory Desk is a separate page beside Operations", async () => {
  const html = await readFile(path.join(here, "index.html"), "utf8");
  const app = await readFile(path.join(here, "assets/app-item4-1008.js"), "utf8");
  const factory = await readFile(path.join(here, "assets/factory-desk.js"), "utf8");
  const css = await readFile(path.join(here, "assets/styles-phase7-0621.css"), "utf8");

  assert.match(html, /id="navFactory"[^>]*>Factory</);
  assert.match(html, /id="page-factory"/);
  assert.match(html, /factory-open-target\.js\?v=0.6.688-suggested-schedule-prefill/);
  assert.match(html, /factory-desk\.js\?v=0.6.687-factory-approve-717/);
  assert.match(html, /"factory":\s*\[\s*"\/assets\/factory-open-target\.js[\s\S]*"\/assets\/factory-desk\.js/);
  assert.doesNotMatch(html, /<script src="\/assets\/factory-desk\.js/);
  assert.match(html, /factory-band-auto/);
  assert.match(html, /factory-band-eyes/);
  assert.match(html, /factory-band-assets/);
  assert.match(html, /factory-band-manual/);
  assert.match(html, /id="factoryCountAutoHigh"/);
  assert.match(html, /id="factoryCountNeedsEyes"/);
  assert.match(html, /id="factoryCountNeedsAssets"/);
  assert.match(html, /id="factoryCountManual"/);
  assert.match(html, /id="factoryPreviewBackdrop"/);
  assert.match(html, /id="factoryPreviewVideo"/);

  const operations = html.indexOf('id="page-operations"');
  const factoryPage = html.indexOf('id="page-factory"');
  const support = html.indexOf('id="page-support"');
  assert.ok(operations > 0 && factoryPage > operations && support > factoryPage);

  assert.match(app, /BUILD_ID = "item4-0.6.688-suggested-schedule-prefill"/);
  assert.match(app, /page === "factory"/);
  assert.match(app, /StudioFactoryDesk\?\.load/);
  assert.match(factory, /StudioFactoryDesk/);
  assert.match(factory, /pin_needs_assets/);
  assert.match(factory, /data-factory-approve/);
  assert.match(factory, /data-factory-approve-content/);
  assert.match(factory, /Approve all \(\$\{ready\.length\}\)/);
  assert.match(factory, /\/api\/outputs\/approve-all/);
  assert.match(factory, /groupContent: true/);
  assert.match(css, /\.factory-content-bar\{/);
  assert.match(css, /\.factory-content-approve\{margin-left:auto/);
  assert.match(factory, /data-factory-send-back/);
  assert.match(factory, /data-factory-send-back-content/);
  assert.match(factory, /Send back to Production/);
  assert.match(factory, /if \(!ready\.length\) \{/);
  assert.match(factory, /ready\.length > 1/);
  assert.match(factory, /send_back_content/);
  assert.match(app, /StudioOpenProductionRequestById/);
  assert.match(app, /StudioOpenPipelineOutputById/);
  assert.match(app, /StudioOpenIdeaById/);
  assert.match(factory, /FactoryOpenTargets/);
  assert.match(factory, /data-factory-delete/);
  assert.match(factory, /data-factory-preview/);
  assert.match(factory, /openFactoryPreview/);
  assert.match(factory, /\/api\/outputs\/\$\{card\.id\}\/preview/);
  assert.match(css, /#page-factory \.factory-lanes\{\s*display:flex;\s*flex-direction:column/);
  assert.match(css, /\.factory-band-auto\{--factory-accent:#0c7a72\}/);
  assert.match(css, /\.factory-band-assets\{--factory-accent:#1f4e89\}/);
  assert.match(css, /\.factory-line\{/);
  assert.doesNotMatch(css, /grid-template-areas:\s*"auto eyes"/);
  assert.match(factory, /factory-line/);
  assert.match(factory, /factoryCountNeedsEyes/);
  assert.match(factory, /\/api\/factory\/desk/);
  assert.match(css, /\.factory-lanes/);
  assert.match(css, /#page-factory/);
  assert.match(css, /\.factory-line-thumb/);
  assert.doesNotMatch(css, /factory-line\{[^}]*max-content/);
  assert.match(css, /overflow-x:hidden/);
});
