"""Service-only native gallery launch reservation. This endpoint does NOT render.

A Runner caller presents the previously obtained exact claim receipt. The
canonical Airtable record and Worker re-verify every identity/hold/source byte.
Default OFF and one-shot. No public media, schedule or publisher integration.
"""
from __future__ import annotations

import hmac
import json
import os
import re

from flask import Blueprint, jsonify, request

from rendering_review.native_gallery_launch_client import (
    NativeGalleryLaunchDenied, reserve_native_gallery_launch,
)

REC = re.compile(r"rec[A-Za-z0-9]{14}\Z")
TOKEN = re.compile(r"[A-Za-z0-9_-]{8,120}\Z")


def _client():
    from airtable.client import AirtableClient
    return AirtableClient()


def create_native_gallery_launch_blueprint(settings, *, client_factory=_client,
                                           reserve=reserve_native_gallery_launch):
    bp = Blueprint("native_gallery_launch_reservation", __name__)

    @bp.post("/jobs/native-gallery/reserve-launch")
    def reserve_gallery_launch():
        if os.environ.get("NATIVE_GALLERY_RUNNER_LAUNCH_ENABLED") != "true":
            return jsonify(ok=False, error="native_gallery_launch_disabled"), 405
        expected = str(settings.get("pipeline_runner_shared_secret") or "").strip()
        supplied = request.headers.get("X-Pipeline-Secret", "")
        if len(expected) < 24 or not supplied or not hmac.compare_digest(expected, supplied):
            return jsonify(ok=False, error="native_gallery_service_auth_denied"), 403
        if not request.is_json:
            return jsonify(ok=False, error="native_gallery_launch_json_required"), 415
        # Chunked bodies must be checked by bytes, not only Content-Length.
        raw = request.get_data(cache=False)
        if len(raw) > 700:
            return jsonify(ok=False, error="native_gallery_launch_body_oversized"), 413
        try:
            body = json.loads(raw)
        except (ValueError, TypeError, UnicodeError):
            return jsonify(ok=False, error="native_gallery_launch_body_invalid"), 400
        if not isinstance(body, dict) or set(body) != {
            "output_id", "job_id", "lease_owner", "lease_fence"
        } or not REC.fullmatch(str(body.get("output_id") or "")) or not TOKEN.fullmatch(
            str(body.get("job_id") or "")
        ) or not TOKEN.fullmatch(str(body.get("lease_owner") or "")) or type(
            body.get("lease_fence")
        ) is not int or body["lease_fence"] < 1:
            return jsonify(ok=False, error="native_gallery_launch_claim_invalid"), 400
        # Only protected environment can choose the Worker URL, secret or
        # consumer. Caller cannot supply generated bytes or plan/Drive URLs.
        claim = {
            **body, "lease_verified": True,
            "render_started": False, "publication_authorized": False,
        }
        try:
            result = reserve(
                client=client_factory(),
                worker_base=os.environ.get("NATIVE_GALLERY_WORKER_BASE_URL", ""),
                shared_secret=os.environ.get("NATIVE_GALLERY_JOB_SHARED_SECRET", ""),
                claim_receipt=claim,
            )
        except NativeGalleryLaunchDenied:
            return jsonify(ok=False,
                           error="native_gallery_launch_requires_reconciliation"), 409
        except Exception:
            return jsonify(ok=False, error="native_gallery_launch_unavailable"), 503
        if not isinstance(result, dict) or result.get("ok") is not True or (
            result.get("may_generate") is not True or
            result.get("publication_authorized") is not False or
            result.get("job_id") != body["job_id"] or
            result.get("output_id") != body["output_id"]
        ):
            return jsonify(ok=False, error="native_gallery_launch_receipt_invalid"), 503
        response = jsonify({
            "ok": True, "intent_reserved": True,
            "job_id": body["job_id"], "output_id": body["output_id"],
            "may_generate": True, "render_started": False,
            "publication_authorized": False,
        })
        response.headers["Cache-Control"] = "no-store"
        return response, 200

    return bp
