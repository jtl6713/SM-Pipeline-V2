"""Exact-profile, one-shot rights catalog registration for native gallery C5/C6.

This does NOT infer ownership from generated bytes. A trusted independent
rights clearance operation must attest the actual provider/terms and new file.
Airtable remains authoritative; Google Drive bytes and permissions are checked
again. Never updates V1 Media Assets or grants Drive permissions.
"""
from __future__ import annotations

import hashlib
import re

from airtable.constants import MEDIA_ASSETS_TABLE
from rendering_review.gallery_authoritative import matching_owned_media, actual_image

REC = re.compile(r"rec[A-Za-z0-9]{14}\Z")
FILE = re.compile(r"[A-Za-z0-9_-]{20,}\Z")
SHA = re.compile(r"[a-f0-9]{64}\Z")
TOKEN = re.compile(r"[A-Za-z0-9_-]{8,120}\Z")


class NativeGalleryRightsDenied(ValueError):
    pass


def deny(reason):
    raise NativeGalleryRightsDenied(reason)


def private_permissions(drive, file_id):
    lookup = getattr(drive, "list_file_permissions", None)
    if not callable(lookup):
        deny("native_gallery_permission_readback_unavailable")
    permissions = lookup(file_id)
    if not isinstance(permissions, list) or not permissions or any(
        not isinstance(row, dict) or row.get("type") not in ("user", "group")
        for row in permissions
    ):
        deny("native_gallery_file_not_private")
    return True


def register_native_gallery_rights(*, client, drive, output_id, profile_id,
                                   content_item_id, job_id, slot_id, file_id,
                                   sha256, byte_count, rights_clearance,
                                   staging_folder_id):
    """Register one new *Owned* record only after independent clearance.

    rights_clearance is trusted server-side callable, NOT a browser flag:
      clearance(output_id, profile_id, content_item_id, job_id, slot_id,
                file_id, sha256) -> {approved: True,
                                    provider: str, rights_basis: str}
    A duplicate/ambiguous catalog write requires reconciliation, never POST retry.
    """
    if not all(REC.fullmatch(str(x or "")) for x in
               (output_id, profile_id, content_item_id, slot_id)) or (
        not TOKEN.fullmatch(str(job_id or "")) or
        not FILE.fullmatch(str(file_id or "")) or
        not FILE.fullmatch(str(staging_folder_id or "")) or
        not SHA.fullmatch(str(sha256 or "")) or
        type(byte_count) is not int or byte_count < 1024 or
        not callable(rights_clearance)
    ):
        deny("native_gallery_rights_input_invalid")
    meta = drive.get_file(file_id)
    if not isinstance(meta, dict) or meta.get("id") != file_id or (
        meta.get("mimeType") != "image/png" or
        meta.get("trashed") is True or
        staging_folder_id not in (meta.get("parents") or [])
    ):
        deny("native_gallery_rights_staging_identity_invalid")
    private_permissions(drive, file_id)
    actual, data = actual_image(drive, file_id)
    if actual["mime_type"] != "image/png" or (
        actual["sha256"] != sha256 or actual["byte_count"] != byte_count
    ):
        deny("native_gallery_rights_drive_bytes_changed")
    clearance = rights_clearance(
        output_id=output_id, profile_id=profile_id,
        content_item_id=content_item_id, job_id=job_id,
        slot_id=slot_id, file_id=file_id, sha256=sha256,
    )
    if not isinstance(clearance, dict) or clearance.get("approved") is not True or (
        not isinstance(clearance.get("provider"), str) or
        not 3 <= len(clearance["provider"]) <= 80 or
        not isinstance(clearance.get("rights_basis"), str) or
        not 8 <= len(clearance["rights_basis"]) <= 500
    ):
        deny("native_gallery_generated_rights_not_cleared")
    key = "ngv2_" + hashlib.sha256(
        ("native-gallery-v2|" + job_id + "|" + slot_id + "|" + sha256).encode()
    ).hexdigest()[:48]
    # Never overwrite an unrelated existing asset. The sole permitted first
    # write is an atomic Airtable upsert on its deterministic transfer ID.
    existing = client.list_records(
        MEDIA_ASSETS_TABLE, formula='{Studio_Transfer_ID}="' + key + '"',
        max_records=2)
    if not isinstance(existing, list) or existing:
        deny("native_gallery_rights_existing_or_ambiguous")
    fields = {
        "Studio_Transfer_ID": key,
        "Asset Name": "Native Gallery V2 " + job_id[:24] + " " + slot_id,
        "Media_Class": "Image",
        "Google Drive File ID": file_id,
        "MIME_Type": "image/png",
        "File_Extension": "png",
        "File_Size_Bytes": byte_count,
        "Asset_Status": "Available",
        "Rights_Status": "Owned",
        "Active": True,
        "Do_Not_Use": False,
        "Content_Profile": [profile_id],
        "Content Items": [content_item_id],
        "Asset_Description": (
            "Private non-Vibe revision; output " + output_id +
            "; job " + job_id + "; slot " + slot_id +
            "; provider " + clearance["provider"] +
            "; rights basis " + clearance["rights_basis"] +
            "; SHA256 " + sha256
        )[:5000],
    }
    try:
        record, created = client.upsert_record(
            MEDIA_ASSETS_TABLE, fields, merge_field="Studio_Transfer_ID",
            typecast=False)
    except Exception as exc:
        raise NativeGalleryRightsDenied(
            "native_gallery_rights_ambiguous_write_reconcile"
        ) from exc
    if created is not True or not REC.fullmatch(str(record.get("id") or "")):
        deny("native_gallery_rights_upsert_not_new")
    # Independent authoritative reload: both deterministic key and exact Drive
    # ownership must hold, with no other row claiming the same file.
    stored = client.get_record(MEDIA_ASSETS_TABLE, record["id"])
    f = stored.get("fields") if isinstance(stored, dict) else None
    if (stored.get("id") != record["id"] or not isinstance(f, dict) or
        f.get("Studio_Transfer_ID") != key or
        f.get("Google Drive File ID") != file_id or
        f.get("Rights_Status") != "Owned" or
        f.get("Asset_Status") != "Available" or
        f.get("Active") is not True or
        f.get("Do_Not_Use") is True or
        f.get("Content_Profile") != [profile_id] or
        f.get("Content Items") != [content_item_id] or
        f.get("MIME_Type") != "image/png" or
        f.get("File_Size_Bytes") != byte_count):
        deny("native_gallery_rights_catalog_readback_failed")
    if matching_owned_media(client, profile_id, file_id) != record["id"]:
        deny("native_gallery_rights_duplicate_drive_identity")
    private_permissions(drive, file_id)
    return {"verified": True, "media_asset_record_id": record["id"],
            "sha256": sha256, "publication_authorized": False}
